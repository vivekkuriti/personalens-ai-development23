from __future__ import annotations

from html import escape

import pandas as pd
import plotly.express as px
import streamlit as st

from database import list_test_runs
from reports.report_generator import ensure_combined_pdf, overall_report_data
from ui.common import OUTCOME_COLORS, SEVERITY_COLORS, SEVERITY_ORDER, fmt_dt, hero, render_finding, run_selector


def render() -> None:
    hero("Overall report", "Compare personas, find shared problems, and prioritise fixes.")
    runs = list_test_runs(50)
    if not runs:
        st.info("No test runs yet.")
        return
    run_id = run_selector(runs, "overall_run", st.session_state.get("selected_run_id"))
    st.session_state["selected_run_id"] = run_id
    data = overall_report_data(run_id)
    if not data:
        st.error("Run not found.")
        return

    st.markdown(f"**{escape(data['website_url'])}** · {fmt_dt(data['test_date'])} · {data['viewport']}  \n"
                f"Goal: {escape(data['journey_goal'])}")
    c = st.columns(6)
    c[0].metric("Personas", data["total_personas"])
    c[1].metric("Successful", data["successful"])
    c[2].metric("Failed", data["failed"])
    c[3].metric("Abandoned", data["abandoned"])
    c[4].metric("UX findings", data["total_findings"])
    c[5].metric("A11y issues", data["total_a11y"])

    if data["status"] == "completed":
        try:
            pdf = ensure_combined_pdf(run_id)
            st.download_button("Download combined PDF report", pdf.read_bytes(), file_name=pdf.name,
                               mime="application/pdf", type="primary", icon=":material/download:")
        except Exception as exc:
            st.warning(f"PDF could not be generated: {exc}")
    else:
        st.info(f"Run status: {data['status']}. The combined PDF is available once the run completes.")

    s = data["synthesis"]
    if s.get("executive_summary"):
        with st.container(border=True):
            st.subheader("Executive summary")
            st.markdown(s["executive_summary"])
            st.caption("Generated by Gemini from recorded results" if s.get("generated_by") == "gemini"
                       else "Generated from recorded findings")

    if data["personas"]:
        df = pd.DataFrame([{
            "Persona": p["persona"]["name"], "Outcome": p["outcome"] or "pending", "Score": p["score"] or 0,
            "Goal progress": p["goal_progress"], "UX findings": len(p["findings"]), "A11y": len(p["violations"]),
            "Steps": p["total_steps"], "Failed steps": p["failed_steps"],
        } for p in data["personas"]])
        left, right = st.columns(2)
        with left:
            with st.container(border=True):
                st.subheader("Experience score by persona")
                fig = px.bar(df, x="Persona", y="Score", color="Outcome", range_y=[0, 100], text="Score",
                             color_discrete_map=OUTCOME_COLORS)
                fig.update_layout(height=320, margin=dict(l=10, r=10, t=10, b=10), legend_title=None)
                st.plotly_chart(fig, use_container_width=True)
        with right:
            with st.container(border=True):
                st.subheader("Findings severity")
                rows = []
                for p in data["personas"]:
                    for f in p["findings"]:
                        rows.append({"Persona": p["persona"]["name"], "Severity": f["severity"]})
                if rows:
                    sdf = pd.DataFrame(rows).value_counts().reset_index(name="Count")
                    fig = px.bar(sdf, x="Persona", y="Count", color="Severity", color_discrete_map=SEVERITY_COLORS,
                                 category_orders={"Severity": SEVERITY_ORDER})
                    fig.update_layout(height=320, margin=dict(l=10, r=10, t=10, b=10), legend_title=None)
                    st.plotly_chart(fig, use_container_width=True)
                else:
                    st.caption("No findings.")
        st.subheader("Persona comparison")
        st.dataframe(df, hide_index=True, use_container_width=True)

    cols = st.columns(2)
    with cols[0]:
        st.subheader("Most problematic pages")
        if data["problem_pages"]:
            st.dataframe(pd.DataFrame(data["problem_pages"], columns=["Page", "Issues"]), hide_index=True,
                         use_container_width=True)
        else:
            st.caption("No page-level issues.")
    with cols[1]:
        st.subheader("Common issues across personas")
        if data["common_issues"]:
            for ci in data["common_issues"]:
                st.markdown(f"- **{escape(ci['issue'])}** <span class='pux-muted'>({ci['type']}) — "
                            f"{', '.join(ci['personas'])}</span>", unsafe_allow_html=True)
        else:
            st.caption("No issue affected more than one persona.")

    if s.get("recommendations"):
        st.subheader("Prioritised recommendations")
        for r in s["recommendations"]:
            with st.container(border=True):
                st.markdown(f"**{r['priority']}. {r['recommendation']}**")
                st.caption(f"{r['rationale']} · Personas: {', '.join(r.get('personas_affected', []))}")

    st.subheader("All findings")
    sev_filter = st.multiselect("Severity", SEVERITY_ORDER, default=SEVERITY_ORDER)
    for f in data["findings"]:
        if f["severity"] in sev_filter:
            render_finding(f, show_persona=True)
